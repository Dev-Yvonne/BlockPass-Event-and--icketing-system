import { Schema, model, Document, Types } from "mongoose";
import crypto from "crypto";

export type BookingStatus = "pending" | "confirmed" | "failed" | "cancelled";

export interface IMintedTicket {
  serial: number;
  assetCode: string;
}

export interface IBookingStellar {
  issuer?: string;
  attendeePublicKey?: string;
  txHash?: string;
  ledger?: number;
}

export interface IBooking extends Document {
  _id: Types.ObjectId;
  user?: Types.ObjectId;
  event: Types.ObjectId;
  attendeeName: string;
  attendeeEmail: string;
  checkoutId: string;
  tierId: Types.ObjectId;
  tierName: string;
  quantity: number;
  totalPrice: number;
  status: BookingStatus;
  ticketCode: string;
  tickets: IMintedTicket[];
  stellar: IBookingStellar;
  failureReason?: string;
  payment: {
    method: "stablecoin" | "local";
    currency: string;
    amount: number;
    /** Local units per USD, when paid in local currency. */
    rate?: number;
    provider: string;
    reference?: string;
    status: "pending" | "paid" | "refunded" | "failed";
  };
  createdAt: Date;
}

const bookingSchema = new Schema<IBooking>(
  {
    // Optional: guests can check out without an account.
    user: { type: Schema.Types.ObjectId, ref: "User", index: true },
    event: { type: Schema.Types.ObjectId, ref: "Event", required: true },
    attendeeName: { type: String, required: true, trim: true },
    attendeeEmail: { type: String, required: true, lowercase: true, trim: true },
    // Generated by the checkout form so a double submit can't buy twice.
    checkoutId: { type: String, required: true, unique: true },
    tierId: { type: Schema.Types.ObjectId, required: true },
    tierName: { type: String, required: true },
    quantity: { type: Number, required: true, min: 1 },
    totalPrice: { type: Number, required: true, min: 0 },
    status: {
      type: String,
      enum: ["pending", "confirmed", "failed", "cancelled"],
      default: "pending",
    },
    // Unguessable, so it can double as the public order reference.
    ticketCode: {
      type: String,
      required: true,
      unique: true,
      default: () => crypto.randomBytes(8).toString("hex").toUpperCase(),
    },
    tickets: [{ _id: false, serial: Number, assetCode: String }],
    stellar: {
      issuer: String,
      attendeePublicKey: String,
      txHash: String,
      ledger: Number,
    },
    failureReason: String,
    payment: {
      method: { type: String, enum: ["stablecoin", "local"], required: true },
      currency: { type: String, required: true },
      amount: { type: Number, required: true },
      rate: Number,
      provider: { type: String, required: true },
      reference: String,
      status: {
        type: String,
        enum: ["pending", "paid", "refunded", "failed"],
        default: "pending",
      },
    },
  },
  { timestamps: { createdAt: true, updatedAt: false } }
);

export default model<IBooking>("Booking", bookingSchema);
